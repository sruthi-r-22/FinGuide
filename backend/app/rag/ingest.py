import glob
import hashlib
import json
import os
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

from pypdf import PdfReader

from backend.app.core.config import settings


DOCUMENT_METADATA_REGISTRY = {
    "RBI_KYC_Master_Directions_Summary.pdf": {
        "title": "RBI KYC Master Directions — Educational Summary",
        "publisher": "FinGuide AI",
    },
    "RBI_Customer_Protection_Limiting_Liability.pdf": {
        "title": "RBI Customer Protection (Limiting Liability) — Educational Summary",
        "publisher": "FinGuide AI",
    },
    "NPCI_UPI_Safety_and_Operating_Guidelines.pdf": {
        "title": "NPCI UPI Safety & Operating Guidelines — Educational Summary",
        "publisher": "FinGuide AI",
    },
    "SBI_Savings_Account_Rules_and_Services.pdf": {
        "title": "SBI Savings Account Rules & Services — Educational Summary",
        "publisher": "FinGuide AI",
    },
}

OFFICIAL_SOURCE_HOSTS = {
    "Reserve Bank of India": {"rbi.org.in", "www.rbi.org.in"},
    "National Payments Corporation of India": {"npci.org.in", "www.npci.org.in"},
}

GENERATED_DEMO_NOTE = (
    "Generated by FinGuide AI for educational demonstration only. "
    "This is not an official publication; no source authenticity or banking "
    "claims have been verified."
)


def _official_metadata_for_pdf(filepath: str) -> dict[str, Any] | None:
    manifest_path = Path(f"{filepath}.source.json")
    if not manifest_path.exists():
        return None

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"Could not read source manifest {manifest_path}: {exc}") from exc
    required = ("title", "publisher", "source_url", "sha256", "verified_by", "verified_on")
    missing = [field for field in required if not manifest.get(field)]
    if missing:
        raise ValueError(
            f"Source manifest {manifest_path} is missing required fields: "
            f"{', '.join(missing)}."
        )

    allowed_hosts = OFFICIAL_SOURCE_HOSTS.get(manifest["publisher"])
    parsed_url = urlparse(manifest["source_url"])
    if parsed_url.scheme != "https" or parsed_url.hostname not in (allowed_hosts or set()):
        raise ValueError(
            f"Source manifest {manifest_path} must link to an HTTPS page on the "
            "official host for its issuing organization."
        )

    digest = hashlib.sha256(Path(filepath).read_bytes()).hexdigest()
    if digest.lower() != str(manifest["sha256"]).lower():
        raise ValueError(
            f"PDF SHA-256 does not match source manifest {manifest_path}; "
            "the existing vector collection was not changed."
        )

    try:
        from datetime import date

        verified_on = date.fromisoformat(str(manifest["verified_on"]))
        published_date = manifest.get("published_date")
        if published_date:
            date.fromisoformat(str(published_date))
    except ValueError as exc:
        raise ValueError(
            f"Source manifest {manifest_path} must use ISO YYYY-MM-DD dates."
        ) from exc

    document_id = str(manifest.get("document_id") or f"sha256:{digest}")
    metadata: dict[str, Any] = {
        "document_id": document_id,
        "document_title": str(manifest["title"]),
        "filename": os.path.basename(filepath),
        "publisher": str(manifest["publisher"]),
        "authority": str(manifest["publisher"]),
        "source_url": str(manifest["source_url"]),
        "content_type": "official_document",
        "is_generated_summary": False,
        "reference_status": "verified",
        "verification_method": "manual_origin_and_sha256_review",
        "verified_by": str(manifest["verified_by"]),
        "last_verified": verified_on.isoformat(),
        "sha256": digest,
    }
    if published_date:
        metadata["published_date"] = str(published_date)
    return metadata


def extract_chunks_from_pdf(
    filepath: str, chunk_size: int = 500, chunk_overlap: int = 100
) -> list[dict[str, Any]]:
    """Extract PDF text page by page while retaining document provenance."""
    if chunk_size <= 0 or chunk_overlap < 0 or chunk_overlap >= chunk_size:
        raise ValueError("chunk_size must be positive and greater than chunk_overlap.")

    filename = os.path.basename(filepath)
    registered_metadata = DOCUMENT_METADATA_REGISTRY.get(filename)
    official_metadata = _official_metadata_for_pdf(filepath)
    if registered_metadata and official_metadata:
        raise ValueError(
            f"{filename} is a known generated demo and cannot be reclassified as "
            "an official document using a sidecar manifest."
        )
    digest = hashlib.sha256(Path(filepath).read_bytes()).hexdigest()
    document_id = f"sha256:{digest}"
    if official_metadata:
        metadata = official_metadata
        document_id = metadata["document_id"]
    elif registered_metadata:
        metadata = {
            "document_id": document_id,
            "document_title": f"FinGuide AI educational demo — {registered_metadata['title']}",
            "filename": filename,
            "publisher": "FinGuide AI",
            "content_type": "generated_demo",
            "is_generated_summary": True,
            "reference_status": "unverified",
            "provenance_note": GENERATED_DEMO_NOTE,
            "sha256": digest,
        }
    else:
        metadata = {
            "document_id": document_id,
            "document_title": Path(filename).stem.replace("_", " "),
            "filename": filename,
            "content_type": "unknown",
            "reference_status": "unknown",
            "sha256": digest,
        }
    try:
        reader = PdfReader(filepath)
    except Exception as exc:
        raise ValueError(f"Could not read PDF {filename}: {exc}") from exc

    chunks: list[dict[str, Any]] = []
    for page_idx, page in enumerate(reader.pages):
        page_text = " ".join((page.extract_text() or "").split())
        start = 0
        page_chunk_index = 0
        while start < len(page_text):
            end = min(start + chunk_size, len(page_text))
            if end < len(page_text):
                last_period = page_text.rfind(". ", start, end)
                if last_period > start + 200:
                    end = last_period + 1
                else:
                    last_space = page_text.rfind(" ", start, end)
                    if last_space > start + 200:
                        end = last_space

            chunk_text = page_text[start:end].strip()
            if chunk_text:
                chunk_metadata = {
                    **metadata,
                    "page_number": page_idx + 1,
                }
                chunks.append(
                    {
                        "id": f"{document_id}:p{page_idx + 1}:c{page_chunk_index}",
                        "text": chunk_text,
                        "metadata": chunk_metadata,
                    }
                )
                page_chunk_index += 1
            start = end - chunk_overlap if end < len(page_text) else len(page_text)

    return chunks


def load_all_document_chunks() -> list[dict[str, Any]]:
    """Scan the configured documents directory and extract all PDF chunks."""
    doc_dir = settings.DOCUMENTS_DIR
    pdf_files = sorted(glob.glob(os.path.join(doc_dir, "*.pdf")))
    all_chunks: list[dict[str, Any]] = []
    seen_chunk_ids: set[str] = set()
    seen_document_hashes: set[str] = set()
    for pdf in pdf_files:
        chunks = extract_chunks_from_pdf(pdf)
        if chunks:
            document_hash = chunks[0]["metadata"]["sha256"]
            if document_hash in seen_document_hashes:
                continue
            seen_document_hashes.add(document_hash)
        for chunk in chunks:
            if chunk["id"] not in seen_chunk_ids:
                seen_chunk_ids.add(chunk["id"])
                all_chunks.append(chunk)
    return all_chunks
